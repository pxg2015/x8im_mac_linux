/// 2026-10-16 构建阻断修复（本机构建环境兼容，不改业务行为）：
/// ① cargo 1.99 不再把 tauri 构建脚本输出的旧式 `cargo:dev={dev}` 注入为 `DEP_TAURI_DEV`
///    （tauri 2.12.3 `build.rs:257` 仍用旧语法），而配套的 `tauri-build 2.7.2`
///    `is_dev()`（lib.rs:609）无条件 `expect("missing cargo:dev instruction")` → 构建失败：
///    `failed to run custom build command for x8im`（exit 101；cargo 不回显 panic 文本，
///    所以下面挂了 panic 钩子把原因打到 stdout，否则只能手跑 build-script-build 才看得到）。
///    这里按 tauri 自身同一判据补齐该变量，语义一致：`dev = !custom-protocol`（build.rs:252-253）。
/// ② windres 预处理需要 `gcc`，而本机 rust GNU 工具链不含 gcc → 已在 `_tools/x8bin` 放
///    `gcc.exe` 垫片（转发 w64devkit 的 gcc，见 `_tools/gcc_wrap.rs`），故该目录必须在 PATH 里。
fn main() {
    let prev = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |info| {
        let loc = info
            .location()
            .map(|l| format!("{}:{}", l.file(), l.line()))
            .unwrap_or_default();
        let msg = info
            .payload()
            .downcast_ref::<&str>()
            .map(|s| (*s).to_string())
            .or_else(|| info.payload().downcast_ref::<String>().cloned())
            .unwrap_or_else(|| "unknown".to_string());
        println!("cargo:warning=[tauri-build panic] {loc} :: {msg}");
        prev(info);
    }));
    if std::env::var_os("DEP_TAURI_DEV").is_none() {
        let dev = std::env::var_os("CARGO_FEATURE_CUSTOM_PROTOCOL").is_none();
        std::env::set_var("DEP_TAURI_DEV", if dev { "true" } else { "false" });
    }

    // Tauri 2.11+：远程页面(im.x8fde.com)调用 generate_handler! 自定义命令强制走 ACL，
    // 必须用 AppManifest 声明命令以生成 allow-* 权限，再在 capabilities/remote.json 放行
    let attrs = tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "get_rustdesk_id",
            "open_rustdesk",
            "close_rustdesk",
            // 2026-10-16 根治：此前漏登记致权限文件/capabilities 双双缺失，
            // 远端页面调用被 ACL 拒绝、tauriInvoke 又吞错 → 前端只看到「no id」，
            // 远程协助自动安装/就绪链路从上线起从未成功过。三处必须同步：
            // 本名单 → permissions/autogenerated/ensure_rustdesk.toml → capabilities/remote.json
            "ensure_rustdesk",
            "open_workbench",
            // 扩展面板（2026-10-24）：小程序独立内嵌窗口（四处同步：本名单 → autogenerated → capabilities/remote.json → generate_handler!）
            "ext_open_window",
            "ext_close_window",
            "ext_focus_window",
            "notify_unread",
            // 2026-10-16 根治「更新条点下载没反应」：open_in_browser 自 1.4.2 引入后
            // 只写了 #[tauri::command] + generate_handler!，漏了本名单 → 无 allow-open-in-browser
            // → 远端页面调用被 ACL 拒绝，dlPkg 的 catch 吞掉 → 用户侧完全无反馈。
            // 老8 实测 exe：open_in_browser FOUND / allow-open-in-browser MISSING。
            "open_in_browser",
            // 桌面端聊天文件下载落盘：带 Bearer 调系统 curl 拉私有文件（WebView <a download> 不生效）
            "download_file",
            "save_bytes",
            // 2026-10-23 截屏：唤系统截图（ms-screenclip）→ 读剪贴板 → PNG base64 回前端
            "screen_clip_grab",
            // 2026-10-16 老8 定（按需启动 / 不用就 kill）：空闲回收本机 X8Assist
            "assist_idle_reap",
            // 2026-10-17 三端对齐：Linux 版不内置 RustDesk，缺组件时一键安装
            // （Windows/mac 包内自带，命令恒返回 already，只为统一前端调用路径）
            "install_rustdesk",
            // 2026-10-17 微信快捷登录：检测本机微信是否在线，前端据此切换「PC 微信确认 / 手机扫码」文案
            "detect_wechat",
            // 2026-10-23 已读回执授权：OS 级窗口焦点，与 notify_unread 同源
            "win_is_focused",
            // 2026-10-22 Windows 静默自动升级（计划任务提权安装，零 UAC 零点击）
            "win_auto_update",
            // 2026-10-25 B 方案：组件式静默升级（不跑 setup.exe，下载签名 portable zip 就地覆盖 + 重拉）
            "win_patch_update",
            // 2026-10-25 无进度通道兜底版：前端构造不出 Channel 时改调这两个，
            // 避免必需 Channel 参数反序列化失败导致命令体一行不执行（假进度事故根因）
            "win_patch_update_nc",
            "win_auto_update_nc",
            // 2026-10-25 Rust 自主升级：前端确认后即返，真实升级在后台线程跑
            "win_upd_start",
            // 2026-10-26 重写：用户点「稍后提醒」→ 落盘静默截止时间，自动复查期间不打扰
            "win_upd_snooze",
            // 2026-10-22 右下角卡通 FDE 浮窗（微信式新消息头像提醒）
            "fde_float_show",
            "fde_float_hide",
            "fde_float_click",
            // 2026-10-23 升级中进度小窗（正在下载 / 已用 / 剩余时间）
            "upd_float_show",
            "upd_float_hide",
            // 2026-10-24 标题栏原生拖动（RDP/虚拟机下 startDragging 的 IPC 延迟兜底）
            "drag_begin",
            // 2026-10-25 标题栏窗控（min/max/close/is_maximized）：绕开运行时不可用的
            // window.__TAURI__.window 命名空间，改走服务端命令 + core.invoke 通道
            "win_minimize",
            "win_toggle_maximize",
            "win_close",
            "win_is_maximized",
            // 2026-10-22 「打开着的会话最小化也不闪」：当前会话来消息时窗口已失焦也要闪托盘+弹气泡
            "away_notice",
        ]),
    );
    if let Err(e) = tauri_build::try_build(attrs) {
        // cargo 不回显 build script 的 panic 文本，这里显式在 stdout 打出原因便于定位
        println!("cargo:warning=tauri-build 失败详情: {e:#}");
        panic!("tauri-build failed");
    }
    // 2026-10-23 链接期补符号：本地 rustup 自带的 mingw(MSVCRT) winpthread 只导出 nanosleep，
    // 而 aws-lc-sys 0.46 调用 nanosleep64（MSVCRT 目标 time_t 已 64 位，struct timespec 与
    // timespec64 布局一致，垫片别名即可）。垫片 .o 由 _tools/x8bin 的 gcc 编出，仅注入最终 exe，
    // 不污染构建脚本（RUSTFLAGS 全局注入会让 build scripts 因缺 winpthread 而链接失败）。
    // 顺序：垫片 .o 必须排在其引用的 nanosleep 所属 libpthread.a 之前，否则静态库已被关闭、
    // 无法回溯解析；故垫片后再重新列出 libpthread.a 让链接器重扫。
    #[cfg(target_os = "windows")]
    {
        println!("cargo:rustc-link-arg=E:/AI/X8_Im/x8im/desktop/src-tauri/nanosleep64_shim.o");
        println!("cargo:rustc-link-arg=-l:libpthread.a");
    }
}
